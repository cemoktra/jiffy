const FIELD_SEPARATOR: char = '\x1f';
const LIST_SEPARATOR: char = '\x1e';
/// Maximum number of unpushed commits listed in the code review header.
const MAX_UNPUSHED_COMMITS: &str = "100";

/// `status`, `source path`, `target path`, `conflict marker` per changed file.
const STATUS_TEMPLATE: &str = r#"status ++ "\x1f" ++ source.path() ++ "\x1f" ++ target.path() ++ "\x1f" ++ if(target.conflict(), "conflict") ++ "\n""#;
const COMMIT_TEMPLATE: &str = r#"commit_id ++ "\x1f" ++ description.first_line() ++ "\x1f" ++ diff.stat().files().map(|f| f.path() ++ "\x1d" ++ f.lines_added() ++ "\x1d" ++ f.lines_removed()).join("\x1e") ++ "\n""#;

/// The two trees a jj diff compares.
#[derive(Clone, Copy, Debug)]
enum DiffRange<'a> {
    /// `@` against its parent: jj's equivalent of uncommitted changes.
    WorkingCopy,
    /// `@` against the given commit.
    FromCommit(&'a str),
    /// `@-` against the given commit: committed changes only.
    Committed(&'a str),
}

impl<'a> DiffRange<'a> {
    fn for_mode(mode: &DiffMode, merge_base: Option<&'a str>) -> Self {
        match (mode, merge_base) {
            (DiffMode::Head, _) | (_, None) => Self::WorkingCopy,
            (DiffMode::MainBranch | DiffMode::OtherBranch(_), Some(base)) => Self::FromCommit(base),
        }
    }

    fn args(self) -> Vec<&'a str> {
        match self {
            Self::WorkingCopy => vec!["-r", "@"],
            Self::FromCommit(commit) => vec!["--from", commit, "--to", "@"],
            Self::Committed(commit) => vec!["--from", commit, "--to", "@-"],
        }
    }

    fn base_revision(self) -> &'a str {
        match self {
            Self::WorkingCopy => "@-",
            Self::FromCommit(commit) | Self::Committed(commit) => commit,
        }
    }
}

#[derive(Debug, PartialEq)]
struct ChangedFile {
    path: String,
    source_path: String,
    status: GitFileStatus,
}

/// Resolves the jj counterpart of git's merge base for `mode`: the fork point of `@` and the
/// base branch (or `trunk()`).
pub(super) async fn compute_merge_base(repo_path: &Path, mode: &DiffMode) -> Result<String> {
    let branch = match mode {
        DiffMode::MainBranch => trunk_name(repo_path).await,
        DiffMode::OtherBranch(branch) => branch.clone(),
        DiffMode::Head => anyhow::bail!("merge base is not applicable for Head mode"),
    };
    fork_point_commit(repo_path, &branch).await
}

pub(super) async fn load_diffs(
    repo_path: &Path,
    mode: &DiffMode,
) -> Result<GitDiffWithBaseContent> {
    let merge_base = match mode {
        DiffMode::Head => None,
        DiffMode::MainBranch | DiffMode::OtherBranch(_) => {
            Some(compute_merge_base(repo_path, mode).await?)
        }
    };
    let range = DiffRange::for_mode(mode, merge_base.as_deref());

    let changed_files = changed_files(repo_path, range, &[], JjSnapshot::Snapshot).await?;
    let patches = split_git_patch(&git_patch(repo_path, range, &[]).await?);

    let mut files = Vec::with_capacity(changed_files.len());
    let mut total_additions = 0;
    let mut total_deletions = 0;
    for changed_file in changed_files {
        let patch = patches
            .get(&patch_key(&changed_file.source_path, &changed_file.path))
            .map(String::as_str)
            .unwrap_or_default();
        let file = file_diff_and_content(repo_path, range, &changed_file, patch).await?;
        total_additions += file.file_diff.additions();
        total_deletions += file.file_diff.deletions();
        files.push(file);
    }

    Ok(GitDiffWithBaseContent {
        files_changed: files.len(),
        files,
        total_additions,
        total_deletions,
    })
}

/// Recomputes the diff for a single file, returning `None` when it is no longer changed.
pub(super) async fn retrieve_diff_state(
    repo_path: &Path,
    relative: String,
    mode: &DiffMode,
    merge_base: Option<&str>,
) -> Result<(String, Option<Arc<FileDiffAndContent>>)> {
    let range = DiffRange::for_mode(mode, merge_base);
    let fileset = [root_file_fileset(&relative)];
    let Some(changed_file) = changed_files(repo_path, range, &fileset, JjSnapshot::Snapshot)
        .await?
        .into_iter()
        .find(|file| file.path == relative)
    else {
        return Ok((relative, None));
    };
    let patch = git_patch(repo_path, range, &fileset).await?;
    let file = file_diff_and_content(repo_path, range, &changed_file, &patch).await?;
    Ok((relative, Some(Arc::new(file))))
}

pub(super) async fn load_metadata(
    repo_path: &Path,
    include_base_branch: bool,
) -> Result<DiffMetadata> {
    let working_copy = working_copy_info(repo_path, JjSnapshot::Snapshot).await?;
    let current_branch_name = working_copy
        .bookmark
        .clone()
        .unwrap_or_else(|| working_copy.change_id.clone());
    let main_branch_name = trunk_name(repo_path).await;

    let against_head = range_metadata(repo_path, DiffRange::WorkingCopy).await?;
    let against_base_branch = if include_base_branch {
        match fork_point_commit(repo_path, &main_branch_name).await {
            Ok(base) => Some(range_metadata(repo_path, DiffRange::FromCommit(&base)).await?),
            Err(err) => {
                log::warn!("Could not determine jj fork point against {main_branch_name}: {err}");
                Some(DiffMetadataAgainstBase::default())
            }
        }
    } else {
        None
    };

    let upstream_ref = match &working_copy.bookmark {
        Some(bookmark) => upstream_bookmark(repo_path, bookmark).await,
        None => None,
    };
    let unpushed_commits = unpushed_commits(repo_path, working_copy.bookmark.as_deref())
        .await
        .unwrap_or_else(|err| {
            log::warn!("Failed to list unpushed jj commits: {err}");
            Vec::new()
        });

    Ok(DiffMetadata {
        main_branch_name,
        current_branch_name,
        against_head,
        against_base_branch,
        has_head_commit: true,
        unpushed_commits,
        upstream_ref,
    })
}

/// Committed changes not yet on the remote: `<bookmark>@origin..<bookmark>` when the bookmark is
/// tracked, otherwise everything since `trunk()` up to the bookmark (or `@-`).
pub(crate) async fn unpushed_commits(
    repo_path: &Path,
    bookmark: Option<&str>,
) -> Result<Vec<Commit>> {
    let revset = match bookmark {
        Some(bookmark) if upstream_bookmark(repo_path, bookmark).await.is_some() => format!(
            "({})..({})",
            remote_bookmark_revset(bookmark),
            bookmark_revset(bookmark)
        ),
        Some(bookmark) => format!("trunk()..({})", bookmark_revset(bookmark)),
        None => "trunk()..@-".to_string(),
    };
    let output = run_jj_command(
        repo_path,
        &[
            "log",
            "-r",
            &revset,
            "--limit",
            MAX_UNPUSHED_COMMITS,
            "--no-graph",
            "-T",
            COMMIT_TEMPLATE,
        ],
        JjSnapshot::Skip,
    )
    .await?;
    Ok(parse_commits(&output))
}

/// Restores the given files in `@` from the diff base: its parent, or the fork point with
/// `branch` when discarding against a base branch.
pub(super) async fn discard_files(
    repo_path: &Path,
    relative_file_infos: &[(String, GitFileStatus)],
    branch: Option<&str>,
) -> Result<()> {
    let mut filesets = Vec::new();
    for (path, status) in relative_file_infos {
        filesets.push(root_file_fileset(path));
        if let GitFileStatus::Renamed { old_path } | GitFileStatus::Copied { old_path } = status {
            filesets.push(root_file_fileset(old_path));
        }
    }
    if filesets.is_empty() {
        return Ok(());
    }

    let base = match branch {
        Some(branch) => Some(fork_point_commit(repo_path, branch).await?),
        None => None,
    };
    let mut args = vec!["restore"];
    if let Some(base) = &base {
        args.extend(["--from", base.as_str(), "--into", "@"]);
    }
    args.push("--");
    args.extend(filesets.iter().map(String::as_str));
    run_jj_command(repo_path, &args, JjSnapshot::Snapshot).await?;
    Ok(())
}

/// Maps discard requests (absolute paths) to repo-relative paths.
pub(super) fn relative_file_infos(
    repo_path: &Path,
    file_infos: Vec<FileStatusInfo>,
) -> Vec<(String, GitFileStatus)> {
    file_infos
        .into_iter()
        .filter_map(|info| {
            let path = info.path.to_local_path()?;
            let relative = path.strip_prefix(repo_path).ok()?.to_str()?.to_string();
            Some((relative, info.status))
        })
        .collect()
}

async fn changed_files(
    repo_path: &Path,
    range: DiffRange<'_>,
    filesets: &[String],
    snapshot: JjSnapshot,
) -> Result<Vec<ChangedFile>> {
    let mut args = vec!["diff"];
    args.extend(range.args());
    args.extend(["-T", STATUS_TEMPLATE, "--"]);
    args.extend(filesets.iter().map(String::as_str));
    let output = run_jj_command(repo_path, &args, snapshot).await?;
    output
        .lines()
        .filter(|line| !line.is_empty())
        .map(parse_changed_file)
        .collect()
}

async fn git_patch(repo_path: &Path, range: DiffRange<'_>, filesets: &[String]) -> Result<String> {
    let mut args = vec!["diff", "--git"];
    args.extend(range.args());
    args.push("--");
    args.extend(filesets.iter().map(String::as_str));
    run_jj_command(repo_path, &args, JjSnapshot::Skip).await
}

async fn range_metadata(repo_path: &Path, range: DiffRange<'_>) -> Result<DiffMetadataAgainstBase> {
    let changed_files = changed_files(repo_path, range, &[], JjSnapshot::Skip).await?;
    let patches = split_git_patch(&git_patch(repo_path, range, &[]).await?);

    let mut total_additions = 0;
    let mut total_deletions = 0;
    let files: Vec<FileChangeEntry> = changed_files
        .iter()
        .map(|file| {
            let (additions, deletions) = patches
                .get(&patch_key(&file.source_path, &file.path))
                .map(|patch| count_patch_lines(patch))
                .unwrap_or_default();
            total_additions += additions;
            total_deletions += deletions;
            FileChangeEntry {
                path: file.path.clone(),
                additions,
                deletions,
            }
        })
        .collect();

    Ok(DiffMetadataAgainstBase {
        aggregate_stats: DiffStats {
            files_changed: files.len(),
            total_additions,
            total_deletions,
        },
        files,
    })
}

async fn file_diff_and_content(
    repo_path: &Path,
    range: DiffRange<'_>,
    changed_file: &ChangedFile,
    patch: &str,
) -> Result<FileDiffAndContent> {
    let mut file_diff = LocalDiffStateModel::file_diff_from_output(
        &changed_file.path,
        &changed_file.status,
        false,
        patch,
    )?;
    // Never read base content for binary files: it can't be rendered inline.
    let content_at_head = if file_diff.is_binary {
        None
    } else {
        match &changed_file.status {
            GitFileStatus::New | GitFileStatus::Untracked => repo_path
                .join(&changed_file.path)
                .is_file()
                .then(String::new),
            GitFileStatus::Modified
            | GitFileStatus::Deleted
            | GitFileStatus::Renamed { .. }
            | GitFileStatus::Copied { .. }
            | GitFileStatus::Conflicted => {
                file_content_at(repo_path, range.base_revision(), &changed_file.source_path).await
            }
        }
    };
    file_diff.is_autogenerated =
        is_file_autogenerated(&changed_file.path, content_at_head.as_deref());
    Ok(FileDiffAndContent {
        file_diff,
        content_at_head,
    })
}

async fn file_content_at(repo_path: &Path, revision: &str, path: &str) -> Option<String> {
    run_jj_command(
        repo_path,
        &[
            "file",
            "show",
            "-r",
            revision,
            "--",
            &root_file_fileset(path),
        ],
        JjSnapshot::Skip,
    )
    .await
    .ok()
}

fn parse_changed_file(line: &str) -> Result<ChangedFile> {
    let mut fields = line.split(FIELD_SEPARATOR);
    let (Some(status), Some(source_path), Some(path)) =
        (fields.next(), fields.next(), fields.next())
    else {
        return Err(anyhow!("Unexpected jj diff status line: {line:?}"));
    };
    let is_conflicted = fields.next().is_some_and(|marker| marker == "conflict");
    let status = if is_conflicted {
        GitFileStatus::Conflicted
    } else {
        match status {
            "added" => GitFileStatus::New,
            "removed" => GitFileStatus::Deleted,
            "renamed" => GitFileStatus::Renamed {
                old_path: source_path.to_string(),
            },
            "copied" => GitFileStatus::Copied {
                old_path: source_path.to_string(),
            },
            _ => GitFileStatus::Modified,
        }
    };
    Ok(ChangedFile {
        path: path.to_string(),
        source_path: source_path.to_string(),
        status,
    })
}

fn patch_key(source_path: &str, path: &str) -> String {
    format!("diff --git a/{source_path} b/{path}")
}

/// Splits a multi-file `jj diff --git` output into per-file patches keyed by their
/// `diff --git a/<source> b/<target>` header line.
fn split_git_patch(output: &str) -> HashMap<String, String> {
    let mut patches = HashMap::new();
    let mut current: Option<(String, String)> = None;
    for line in output.split_inclusive('\n') {
        if line.starts_with("diff --git ") {
            if let Some((header, patch)) = current.take() {
                patches.insert(header, patch);
            }
            current = Some((line.trim_end_matches('\n').to_string(), String::new()));
        }
        if let Some((_, patch)) = current.as_mut() {
            patch.push_str(line);
        }
    }
    if let Some((header, patch)) = current {
        patches.insert(header, patch);
    }
    patches
}

/// Counts added and removed lines in a single-file patch.
fn count_patch_lines(patch: &str) -> (usize, usize) {
    let mut in_hunk = false;
    let mut additions = 0;
    let mut deletions = 0;
    for line in patch.lines() {
        if line.starts_with("@@") {
            in_hunk = true;
        } else if in_hunk && line.starts_with('+') {
            additions += 1;
        } else if in_hunk && line.starts_with('-') {
            deletions += 1;
        }
    }
    (additions, deletions)
}

fn parse_commits(output: &str) -> Vec<Commit> {
    output
        .lines()
        .filter_map(|line| {
            let mut fields = line.split(FIELD_SEPARATOR);
            let hash = fields.next()?.trim().to_string();
            if hash.is_empty() {
                return None;
            }
            let subject = fields.next().unwrap_or_default().to_string();
            let files: Vec<FileChangeEntry> = fields
                .next()
                .unwrap_or_default()
                .split(LIST_SEPARATOR)
                .filter_map(|entry| {
                    let mut parts = entry.split('\x1d');
                    let path = parts.next().filter(|path| !path.is_empty())?.to_string();
                    let additions = parts.next()?.parse().ok()?;
                    let deletions = parts.next()?.parse().ok()?;
                    Some(FileChangeEntry {
                        path,
                        additions,
                        deletions,
                    })
                })
                .collect();
            Some(Commit {
                hash,
                subject,
                files_changed: files.len(),
                additions: files.iter().map(|file| file.additions).sum(),
                deletions: files.iter().map(|file| file.deletions).sum(),
                files,
            })
        })
        .collect()
}

/// jj's counterpart of `git::compute_unpushed_state`.
pub(crate) async fn unpushed_state(repo_path: &Path) -> (Vec<Commit>, Option<String>) {
    let bookmark = working_copy_info(repo_path, JjSnapshot::Skip)
        .await
        .ok()
        .and_then(|info| info.bookmark);
    let upstream_ref = match &bookmark {
        Some(bookmark) => upstream_bookmark(repo_path, bookmark).await,
        None => None,
    };
    let commits = unpushed_commits(repo_path, bookmark.as_deref())
        .await
        .unwrap_or_default();
    (commits, upstream_ref)
}

/// Files changed in the working-copy change, i.e. what `jj commit` would record.
pub(crate) async fn working_copy_file_entries(repo_path: &Path) -> Result<Vec<FileChangeEntry>> {
    working_copy_info(repo_path, JjSnapshot::Snapshot).await?;
    Ok(range_metadata(repo_path, DiffRange::WorkingCopy)
        .await?
        .files)
}

/// Files changed by committed changes since the fork point with `trunk()`, excluding the
/// working-copy change.
pub(crate) async fn committed_branch_file_entries(
    repo_path: &Path,
) -> Result<Vec<FileChangeEntry>> {
    let trunk = trunk_name(repo_path).await;
    let Ok(fork_point) = fork_point_commit(repo_path, &trunk).await else {
        return Ok(Vec::new());
    };
    let metadata = range_metadata(repo_path, DiffRange::Committed(&fork_point)).await?;
    Ok(metadata.files)
}

